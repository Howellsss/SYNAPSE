#!/bin/sh
# Single-file copies of edge functions that import local files, for pasting into the Supabase
# dashboard's code editor (which only deploys the files you add there). Regenerate after edits.
cd "$(dirname "$0")/.."
out=supabase/paste/send-email.ts
{
  echo "// GENERATED by scripts/build-paste-functions.sh from supabase/functions/send-email/ (index.ts + replies.ts)."
  echo "// Paste this whole file as send-email's only file (index.ts) in the Supabase dashboard. Don't edit here."
  echo
  grep -v '^import .* from "./replies.ts";$' supabase/functions/send-email/index.ts
  echo
  echo "// ---------- replies.ts ----------"
  cat supabase/functions/send-email/replies.ts
} > "$out"
echo "wrote $out"
