#!/usr/bin/env python3
"""Writes supabase/check-missing-updates.sql: a read-only query that lists which migrations
haven't been applied to a database (missing tables, columns, functions, triggers, policies,
or an older version of a function). Run after adding a migration: python3 scripts/build-missing-check.py"""
import re, glob, os, hashlib
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
state = {}  # key -> migration that last created it
SKIP = ('20260905042433', '20260905042505')  # data only, skipped by build-supabase-setup.sh
pat = re.compile(r'''
 (?P<ct>CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:public\.)?"?(?P<ct_t>\w+)"?\s*\()
|(?P<dt>DROP\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:public\.)?"?(?P<dt_t>\w+)"?)
|(?P<at>ALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?(?:public\.)?"?(?P<at_t>\w+)"?\s+(?P<at_body>[^;]*);)
|(?P<cf>CREATE\s+(?:OR\s+REPLACE\s+)?FUNCTION\s+(?:public\.)?"?(?P<cf_n>\w+)"?\s*\()
|(?P<df>DROP\s+FUNCTION\s+(?:IF\s+EXISTS\s+)?(?:public\.)?"?(?P<df_n>\w+)"?)
|(?P<cg>CREATE\s+TRIGGER\s+"?(?P<cg_n>\w+)"?)
|(?P<dg>DROP\s+TRIGGER\s+(?:IF\s+EXISTS\s+)?"?(?P<dg_n>\w+)"?)
|(?P<cp>CREATE\s+POLICY\s+"(?P<cp_n>[^"]+)"\s+ON\s+(?:(?P<cp_s>\w+)\.)?"?(?P<cp_t>\w+)"?)
|(?P<dp>DROP\s+POLICY\s+(?:IF\s+EXISTS\s+)?"(?P<dp_n>[^"]+)"\s+ON\s+(?:(?P<dp_s>\w+)\.)?"?(?P<dp_t>\w+)"?)
''', re.I | re.X | re.S)
for f in sorted(glob.glob(root + '/supabase/migrations/*.sql')):
    name = os.path.basename(f)
    if name.startswith(SKIP): continue
    raw = open(f).read()
    # Comments blanked to spaces (same length), so positions match the original text.
    sql = re.sub(r'--[^\n]*', lambda c: ' ' * len(c.group(0)), raw)
    sql = re.sub(r'/\*.*?\*/', lambda c: re.sub(r'[^\n]', ' ', c.group(0)), sql, flags=re.S)
    for m in pat.finditer(sql):
        g = m.groupdict()
        if g['ct']: state[('table', 'public', g['ct_t'], None)] = name
        elif g['dt']: state.pop(('table', 'public', g['dt_t'], None), None); [state.pop(k) for k in list(state) if k[0] in ('column',) and k[2] == g['dt_t']]
        elif g['at']:
            t = g['at_t']
            for c in re.finditer(r'ADD\s+COLUMN\s+(?:IF\s+NOT\s+EXISTS\s+)?"?(\w+)"?', g['at_body'], re.I): state[('column', 'public', t, c.group(1))] = name
            for c in re.finditer(r'DROP\s+COLUMN\s+(?:IF\s+EXISTS\s+)?"?(\w+)"?', g['at_body'], re.I): state.pop(('column', 'public', t, c.group(1)), None)
        elif g['cf']:
            # The body, to tell an older version from this one.
            body = None
            mm = re.compile(r'\bAS\s+(\$\w*\$)(.*?)\1', re.S | re.I).search(raw, m.end())
            semi = sql.find(';', m.end())
            if mm and (semi < 0 or mm.start() < semi or mm.start() < sql.find(')', m.end()) + 400):
                body = mm.group(2)
            state[('function', 'public', g['cf_n'], hashlib.md5(body.encode()).hexdigest() if body is not None else None)] = name
            for k in [k for k in state if k[0] == 'function' and k[2] == g['cf_n'] and k[3] != state and k != ('function', 'public', g['cf_n'], hashlib.md5(body.encode()).hexdigest() if body is not None else None)]:
                state.pop(k)
        elif g['df']:
            for k in [k for k in state if k[0] == 'function' and k[2] == g['df_n']]: state.pop(k)
        elif g['cg']: state[('trigger', None, g['cg_n'], None)] = name
        elif g['dg']: state.pop(('trigger', None, g['dg_n'], None), None)
        elif g['cp']: state[('policy', (g['cp_s'] or 'public').lower(), g['cp_t'], g['cp_n'])] = name
        elif g['dp']: state.pop(('policy', (g['dp_s'] or 'public').lower(), g['dp_t'], g['dp_n']), None)
rows = sorted(((mig,) + k for k, mig in state.items()), key=lambda r: r[0])


# Raw file links for pasting, and the updates that can't simply be run a second time (tested by
# running every migration twice on a test database).
RAW = 'https://raw.githubusercontent.com/Howellsss/SYNAPSE/claude/upbeat-thompson-4qxy0n/supabase/migrations/'
NOT_RERUNNABLE = {'20260902225000_add_workspace_settings_table.sql',
                  '20260904032958_add_public_messages_and_contacts_select_policies.sql.sql',
                  '20260906223635_add_forms_module_inactive_status_and_usage_tracking.sql'}
q = lambda x: "'" + x.replace("'", "''") + "'" if x is not None else 'null'
values = ",\n".join(f"  ({q(m)},{q(k)},{q(s)},{q(a)},{q(b)})" for m, k, s, a, b in rows)
sql = """-- SYNAPSE: which database updates are missing on this project?
-- Read only: it changes nothing. Generated by scripts/build-missing-check.py from supabase/migrations.
-- Run it in the Supabase SQL Editor. Each row is an update (a file in supabase/migrations) with
-- something missing or out of date; run those files, oldest first, then run this again.
with expected(migration, kind, sch, a, b) as (values
""" + values + """
), missing as (
  select e.*, case e.kind
      when 'function' then case when exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = e.a)
                                then 'older version of ' || e.a || '()' else 'function ' || e.a || '()' end
      when 'column' then 'column ' || e.a || '.' || e.b
      when 'policy' then 'policy "' || e.b || '" on ' || e.sch || '.' || e.a
      else e.kind || ' ' || e.a end as what
  from expected e where not case e.kind
    when 'table' then to_regclass('public.' || quote_ident(e.a)) is not null
    when 'column' then exists (select 1 from information_schema.columns c where c.table_schema = 'public' and c.table_name = e.a and c.column_name = e.b)
    when 'function' then exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = e.a and (e.b is null or md5(p.prosrc) = e.b))
    when 'trigger' then exists (select 1 from pg_trigger t where t.tgname = e.a and not t.tgisinternal)
    when 'policy' then exists (select 1 from pg_policies p where p.schemaname = e.sch and p.tablename = e.a and p.policyname = e.b)
  end
)
select migration as "update to run (oldest first)",
       case when migration in (""" + ", ".join(q(n) for n in sorted(NOT_RERUNNABLE)) + """) then 'ask before running: partly applied'
            else '""" + RAW + """' || migration end as "file to paste",
       string_agg(what, ', ' order by what) as "what's missing"
from missing group by migration
union all
select 'Nothing missing: every update is applied', null, null where not exists (select 1 from missing)
order by 1;
"""
out = os.path.join(root, 'supabase', 'check-missing-updates.sql')
open(out, 'w').write(sql)
print(f'wrote supabase/check-missing-updates.sql: {len(rows)} checks across {len({r[0] for r in rows})} updates')
